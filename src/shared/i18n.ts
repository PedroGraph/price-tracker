/**
 * Tiny i18n: the English text is the key, Spanish comes from the table below, and
 * anything missing falls back to English. `{name}` placeholders are filled from `vars`.
 */
export type Lang = 'en' | 'es'

export const LOCALES: Record<Lang, string> = { en: 'en-US', es: 'es-CO' }

export function translate(lang: Lang, text: string, vars?: Record<string, string | number>): string {
  const s = lang === 'es' ? (ES[text] ?? text) : text
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s
}

